export const createProductController = async (req, res) => {
  try {
    const fields = req.fields || {};
    const files = req.files || {};
    const { name, description, price, category, quantity, shipping } = fields;
    const { photo } = files;

    // validation
    switch (true) {
      case !name:
        return res.status(400).send({ success: false, error: "Name is Required" });
      case !description:
        return res.status(400).send({ success: false, error: "Description is Required" });
      case !price:
        return res.status(400).send({ success: false, error: "Price is Required" });
      case !category:
        return res.status(400).send({ success: false, error: "Category is Required" });
      case !quantity:
        return res.status(400).send({ success: false, error: "Quantity is Required" });
      case photo && photo.size > 1000000:
        return res
          .status(400)
          .send({ success: false, error: "Photo should be less than 1MB" });
    }

    const productPayload = {
      name,
      description,
      price: Number(price),
      category,
      quantity: Number(quantity),
      slug: slugify(name),
    };
    if (shipping !== undefined && shipping !== "") {
      productPayload.shipping = shipping === "1" || shipping === true;
    }

    const products = new productModel(productPayload);
    if (photo && photo.path) {
      products.photo.data = fs.readFileSync(photo.path);
      products.photo.contentType = photo.type;
    }
    await products.save();
    res.status(201).send({
      success: true,
      message: "Product Created Successfully",
      products,
    });
  } catch (error) {
    console.log("Create product error:", error);
    res.status(500).send({
      success: false,
      message: "Error in creating product",
      error: error.message,
    });
  }
};

